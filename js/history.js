export function getMasteryRank(count) {
  if (count >= 100) return { level: 4, badge: '👑', label: 'Sovereign', mult: 2.0 };
  if (count >= 40) return { level: 3, badge: '★★★', label: 'Museum Grade', mult: 1.5 };
  if (count >= 15) return { level: 2, badge: '★★☆', label: 'Curated', mult: 1.25 };
  if (count >= 1) return { level: 1, badge: '★☆☆', label: 'Acquired', mult: 1.0 };
  return { level: 0, badge: 'LOCKED', label: 'Undiscovered', mult: 0 };
}

export function formatEstateMoney(num) {
  if (num >= 1_000_000) return `$${(num / 1_000_000).toFixed(2)}M`;
  if (num >= 10_000) return `$${Math.round(num / 1_000)}K`;
  return `$${Math.round(num).toLocaleString()}`;
}
